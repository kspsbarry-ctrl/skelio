window.SKELIO.sampleCameraPath = function sampleCameraPath(progress) {
  const path = window.SKELIO_CAMERA_PATH;
  const clamped = Math.max(0, Math.min(1, Number(progress) || 0));
  for (let i = 0; i < path.length - 1; i++) {
    const a = path[i];
    const b = path[i + 1];
    if (clamped >= a.p && clamped <= b.p) {
      const span = Math.max(1e-6, b.p - a.p);
      const u = (clamped - a.p) / span;
      const s = u * u * (3 - 2 * u);
      return {
        progress: clamped,
        yaw: a.yaw + (b.yaw - a.yaw) * s,
        pitch: a.pitch + (b.pitch - a.pitch) * s,
        radiusRatio: a.radiusRatio + (b.radiusRatio - a.radiusRatio) * s,
        heightOffset: a.heightOffset + (b.heightOffset - a.heightOffset) * s,
        label: u < 0.5 ? a.label : b.label
      };
    }
  }
  const last = path[path.length - 1];
  return {
    progress: clamped,
    yaw: last.yaw,
    pitch: last.pitch,
    radiusRatio: last.radiusRatio,
    heightOffset: last.heightOffset,
    label: last.label
  };
};

